    INNER JOIN RAW_DADO_OPERACAO DOP ON DOP.NUM_ID_OPERACAO = O.NUM_ID_OPERACAO
    INNER JOIN RAW_LANCAMENTO LAN ON LAN.NUM_ID_OPERACAO = O.NUM_ID_OPERACAO
