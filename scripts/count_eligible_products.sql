            UNION ALL
            SELECT CP.NUM_IF
            FROM RAW_CARTEIRA_PARTICIPANTE CP
            GROUP BY CP.NUM_IF, CP.COD_TIPO_POSICAO_CARTEIRA, CP.NUM_SISTEMA, CP.NUM_CONTA_PARTICIPANTE
            HAVING COUNT(*) > 1
