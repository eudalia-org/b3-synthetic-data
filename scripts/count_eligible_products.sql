SELECT 'cdb_simplificado' AS produto, COUNT(DISTINCT NUM_IF) AS qtd_elegiveis
FROM (
    WITH FILTRO_BASE AS (
        SELECT DISTINCT IFE.NUM_IF
        FROM RAW_INSTRUMENTO_FINANCEIRO IFE
        INNER JOIN RAW_TITULO TIT ON TIT.NUM_IF = IFE.NUM_IF
        INNER JOIN RAW_CONDICAO_IF CIF ON CIF.NUM_IF = IFE.NUM_IF
        INNER JOIN RAW_RESGATE RES ON RES.NUM_CONDICAO_IF = CIF.NUM_CONDICAO_IF
        WHERE IFE.NUM_TIPO_IF = 49
          AND TIT.COD_TIPO_ESCALONAMENTO IS NULL
          AND RES.COD_COND_RESGATE = 'SEM TABELA'
          AND IFE.DAT_EXCLUSAO IS NULL
          AND CIF.DAT_EXCLUSAO IS NULL
          AND RES.DAT_EXCLUSAO IS NULL
    ),
    FLAGS_IF AS (
        SELECT DISTINCT C.NUM_IF
        FROM RAW_CONDICAO_IF C
        INNER JOIN FILTRO_BASE FB ON FB.NUM_IF = C.NUM_IF
        WHERE C.DAT_EXCLUSAO IS NULL AND C.COD_TIPO_CONDICAO_IF <> 20
    ),
    DEP_IF AS (
        SELECT DISTINCT DP.NUM_IF
        FROM RAW_DEPOSITO_AUTOMATICO_IF DP
        INNER JOIN FILTRO_BASE FB ON FB.NUM_IF = DP.NUM_IF
        WHERE DP.NUM_IF IS NOT NULL
    ),
    OPER_REGISTRO AS (
        SELECT DISTINCT O.NUM_IF
        FROM RAW_OPERACAO O
        INNER JOIN RAW_TIPO_OPER_OBJETO_SERV TOS
            ON TOS.NUM_ID_TIPO_OPER_OBJETO_SERV = O.NUM_ID_TIPO_OPER_OBJETO_SERV
        INNER JOIN RAW_TIPO_OPERACAO TOP ON TOP.NUM_ID_TIPO_OPERACAO = TOS.NUM_ID_TIPO_OPERACAO
        WHERE TRIM(TOP.COD_TIPO_OPERACAO) = '1'
          AND TOS.NUM_ID_OBJETO_SERVICO = 44
          AND TRIM(TOS.IND_DISPONIVEL_IDENTIFICACAO) = 'S'
    )
    SELECT DISTINCT F.NUM_IF
    FROM FLAGS_IF F
    INNER JOIN DEP_IF DEP ON DEP.NUM_IF = F.NUM_IF
    INNER JOIN OPER_REGISTRO ORG ON ORG.NUM_IF = F.NUM_IF
    INNER JOIN RAW_OPERACAO O ON O.NUM_IF = F.NUM_IF
    INNER JOIN RAW_DADO_OPERACAO DOP ON DOP.NUM_ID_OPERACAO = O.NUM_ID_OPERACAO
    INNER JOIN RAW_LANCAMENTO LAN ON LAN.NUM_ID_OPERACAO = O.NUM_ID_OPERACAO
    INNER JOIN RAW_ESPECIFICACAO ESP ON ESP.NUM_ID_OPERACAO = O.NUM_ID_OPERACAO
    INNER JOIN RAW_ESPECIFICACAO_COMITENTE EPC ON EPC.NUM_ID_ESPECIFICACAO = ESP.NUM_ID_ESPECIFICACAO
) elegiveis;
-- END COUNT: cdb_simplificado

